// Generates packages/runtime-sdk-independent avatar geometry for PSM's project identity
// plugin, copied from OpenBot's avatar library so both apps draw the same faces.
//
// Usage (needs network, run from the repo root):
//   mkdir -p /tmp/bloub-gen && cd /tmp/bloub-gen
//   npm init -y && npm i @norbert_bodziony/bloub@0.4.1 solid-js@2.0.0-rc.0 @solidjs/web@2.0.0-rc.0
//   node <repo>/extensions/psm-project-identity/scripts/generate-bloub-table.mjs > \
//     <repo>/extensions/psm-project-identity/bloubTable.ts
//
// The library is MIT licensed (see the plugin README); only its rendered geometry is
// stored here, so PSM needs no Solid runtime and no third-party dependency at runtime.

import { renderToString, createComponent } from '@solidjs/web'
import {
  BloubBot,
  COLORS,
  EXPRESSIONS,
  SHAPES,
} from '@norbert_bodziony/bloub'

/** OpenBot's hue -> colour mapping (@openbot/brand/src/bloub-avatar.ts). */
const HUE_COLOR_IDS = {
  0: 'rouge',
  30: 'orange',
  55: 'ambre',
  100: 'vert',
  150: 'vert',
  185: 'turquoise',
  215: 'bleu',
  245: 'violet',
  280: 'violet',
  320: 'rose',
}

const UNSUPPORTED_SHAPE = 'goutte'

const render = (shape, expression) =>
  renderToString(() =>
    createComponent(BloubBot, {
      size: 100,
      shape,
      color: 'rose',
      expression,
      frozenAt: 0,
      ariaLabel: '',
    }),
  )

const bodyPathOf = (html) => {
  const matches = [...html.matchAll(/<path[^>]*d="([^"]*)"/g)].map((match) => match[1])
  const body = matches.sort((a, b) => b.length - a.length)[0]
  if (!body) throw new Error('no body path in render')
  return body
}

const eyesOf = (html) => {
  const eyes = [...html.matchAll(/<path[^>]*d="([^"]*)" transform="([^"]*)"/g)].map((match) => ({
    d: match[1],
    transform: match[2],
  }))
  if (eyes.length !== 2) throw new Error(`expected 2 eyes, got ${eyes.length}`)
  return eyes
}

const shapeIds = SHAPES.map((shape) => shape.id)
const supportedShapes = shapeIds.filter((id) => id !== UNSUPPORTED_SHAPE)
const expressionIds = EXPRESSIONS.map((expression) => expression.id)

const bodyPaths = shapeIds.map((shape) => bodyPathOf(render(shape, expressionIds[0])))

const eyePaths = expressionIds.map((expression) =>
  eyesOf(render(shapeIds[0], expression)).map((eye) => eye.d),
)

const eyeTransforms = shapeIds.map((shape) =>
  expressionIds.map((expression) => eyesOf(render(shape, expression)).map((eye) => eye.transform)),
)

const hexByColorId = Object.fromEntries(COLORS.map((color) => [color.id, color.hex]))
const hueHexes = Object.entries(HUE_COLOR_IDS).map(([hue, colorId]) => {
  const hex = hexByColorId[colorId]
  if (!hex) throw new Error(`no hex for colour ${colorId}`)
  return [Number(hue), hex]
})

const automaticColors = ['rouge', 'orange', 'ambre', 'vert', 'turquoise', 'bleu', 'violet', 'rose'].map((colorId) => {
  const hex = hexByColorId[colorId]
  if (!hex) throw new Error(`no hex for colour ${colorId}`)
  return hex
})

const q = (value) => JSON.stringify(value)
/** JSON array on one line with readable separators; never rewrites inside strings. */
const qArray = (values) => `[${values.map((value) => q(value)).join(', ')}]`

process.stdout.write(`// GENERATED by scripts/generate-bloub-table.mjs - do not edit by hand.
// Geometry from @norbert_bodziony/bloub@0.4.1 (MIT, Jérémy Perret), the same library
// OpenBot renders its agent avatars with. Regenerate only when that library changes.

export const BLOUB_HUE_HEX: Readonly<Record<number, string>> = {
${hueHexes.map(([hue, hex]) => `  ${hue}: ${q(hex)},`).join('\n')}
}

export const BLOUB_AUTOMATIC_COLORS: readonly string[] = ${qArray(automaticColors)}

export const BLOUB_SHAPES: readonly string[] = ${qArray(shapeIds)}

/** Bodies are parallel to BLOUB_SHAPES. */
export const BLOUB_BODY_PATHS: readonly string[] = [
${bodyPaths.map((path) => `  ${q(path)},`).join('\n')}
]

export const BLOUB_EXPRESSIONS: readonly string[] = ${qArray(expressionIds)}

/** [expressionIndex] = [leftEyePath, rightEyePath]; they differ for asymmetric expressions. */
export const BLOUB_EYE_PATHS: readonly (readonly string[])[] = [
${eyePaths.map((pair) => `  ${qArray(pair)},`).join('\n')}
]

/** [shapeIndex][expressionIndex] = [leftTransform, rightTransform]. */
export const BLOUB_EYE_TRANSFORMS: readonly (readonly (readonly string[])[])[] = [
${eyeTransforms
  .map(
    (perExpression) =>
      `  [\n${perExpression.map((pair) => `    ${qArray(pair)},`).join('\n')}\n  ],`,
  )
  .join('\n')}
]

export const BLOUB_SUPPORTED_SHAPES: readonly string[] = ${qArray(supportedShapes)}
export const BLOUB_UNSUPPORTED_SHAPE = ${q(UNSUPPORTED_SHAPE)}
`)
