// Generates the vendored brand-glyph table for PSM's project-icons plugin from
// simple-icons, so the plugin ships real project logos (favicon-style marks)
// without a runtime dependency and without emoji.
//
// Usage (needs network):
//   mkdir -p /tmp/psm-icons-gen && cd /tmp/psm-icons-gen
//   npm init -y && npm i simple-icons@16.36.0
//   node <repo>/extensions/psm-project-icons/scripts/generate-icon-table.mjs > \
//     <repo>/extensions/psm-project-icons/iconTable.ts
// (the script resolves simple-icons from the current directory's node_modules)
//
// simple-icons is CC0-1.0; only the rendered glyph paths and brand hex colors are
// stored here. Regenerate when PSM adds a new project kind.

import { createRequire } from 'node:module'
import path from 'node:path'

const KINDS = {
  tauri: 'tauri',
  rust: 'rust',
  go: 'go',
  python: 'python',
  java: 'openjdk',
  dotnet: 'dotnet',
  php: 'php',
  ruby: 'ruby',
  'c-cpp': 'cplusplus',
  nextjs: 'nextdotjs',
  react: 'react',
  vue: 'vuedotjs',
  svelte: 'svelte',
  angular: 'angular',
  node: 'nodedotjs',
}

// Resolved from the working directory so the documented temp-dir usage works.
const requireFromCwd = createRequire(path.join(process.cwd(), 'package.json'))
const icons = requireFromCwd('simple-icons')

const rows = Object.entries(KINDS).map(([kind, slug]) => {
  const exportName = `si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`
  const icon = icons[exportName]
  if (!icon) {
    throw new Error(`simple-icons has no icon for slug "${slug}" (looked up ${exportName})`)
  }
  return { kind, title: icon.title, hex: icon.hex, path: icon.path }
})

const lines = rows.map(
  ({ kind, title, hex, path }) =>
    `  ${JSON.stringify(kind)}: { title: ${JSON.stringify(title)}, hex: ${JSON.stringify(hex)}, path: ${JSON.stringify(path)} },`,
)

process.stdout.write(`// Generated by scripts/generate-icon-table.mjs from simple-icons (CC0-1.0).
// Only the rendered glyph geometry is vendored here, so the plugin needs no
// simple-icons runtime dependency. Do not edit by hand.

export interface IconGlyph {
  title: string
  /** Brand color hex without the leading #. */
  hex: string
  /** simple-icons 24x24 viewBox path data. */
  path: string
}

export const ICON_GLYPHS: Record<string, IconGlyph> = {
${lines.join('\n')}
}
`)
